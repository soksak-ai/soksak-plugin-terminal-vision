#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workflow = fs.readFileSync(path.join(root, ".github/workflows/release.yml"), "utf8");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "plugin.json"), "utf8"));
const pkg = JSON.parse(fs.readFileSync(path.join(root, "frontend/package.json"), "utf8"));
if (manifest.version !== pkg.version) throw new Error("plugin manifest and frontend package versions differ");
if (!pkg.scripts?.verify?.includes("node build.mjs --check") || /\bgit\b/.test(pkg.scripts.verify)) throw new Error("plugin verification must compare generated bytes without a Git checkout");
const nodeVersion = fs.readFileSync(path.join(root, ".node-version"), "utf8").trim();
const makefile = fs.readFileSync(path.join(root, "Makefile"), "utf8");
const preflight = fs.readFileSync(path.join(root, "scripts/check-build-environment.sh"), "utf8");
if (/pnpm_executable|pnpmExecutable/.test(preflight)) throw new Error("preflight must judge the effective repository-selected pnpm");
const requireText = (value, label) => { if (!workflow.includes(value)) throw new Error(`release workflow is missing ${label}: ${value}`); };
if (nodeVersion !== pkg.engines.node) throw new Error("Node owner file and package engine differ");
for (const target of ["preflight", "lock", "prepare", "build", "verify", "require-tooling", "require-out", "require-store", "release", "attest"]) {
  if (!new RegExp(`^${target}:`, "m").test(makefile)) throw new Error(`Makefile target is missing: ${target}`);
}
if (!/^lock: guard preflight$/m.test(makefile) || !makefile.includes("pnpm --dir frontend install --lockfile-only")) {
  throw new Error("Makefile must own deterministic lockfile regeneration");
}
for (const boundary of ["command -v soksak-sdk", "STORE", "OUT", "release.json", "--store"]) {
  if (!makefile.includes(boundary)) throw new Error(`Makefile release boundary is missing: ${boundary}`);
}
if (/SDK_ROOT|SDK_RELEASE|TOOLING_ROOT|TOOLING_RELEASE/.test(makefile)) throw new Error("SDK tooling is selected by PATH, not Make path inputs");
if (!/^SDK_VERSION := 0\.0\.19$/m.test(makefile)) throw new Error("Makefile must select SDK 0.0.19");
if (typeof manifest.spec === "string" || "schema" in manifest) throw new Error("plugin manifest repeats schema metadata");
if (manifest.appVersionRequirement !== "0.0.1") throw new Error("plugin app version requirement must be exact 0.0.1");
if (!Array.isArray(manifest.runtimeDependencies?.sidecars) || manifest.runtimeDependencies.sidecars.length !== 7) throw new Error("the terminal requires the PTY and every engine Sidecar it offers (7 exact releases)");
for (const sidecar of manifest.runtimeDependencies.sidecars) if (Object.keys(sidecar).sort().join(",") !== "id,version") throw new Error("Sidecar dependencies declare {id, version} only; size and sha256 belong to the release document");
if (!/^\d+\.\d+\.\d+$/.test(pkg.engines?.node ?? "") || !/^pnpm@\d+\.\d+\.\d+$/.test(pkg.packageManager ?? "")) throw new Error("release toolchain must be exact");
if ("pnpm" in pkg) throw new Error("pnpm 11 settings belong in pnpm-workspace.yaml");
for (const obsolete of ["release/dependencies.json", "release/source-dependencies.json"]) {
  if (fs.existsSync(path.join(root, obsolete))) throw new Error(`${obsolete} is obsolete`);
}
requireText("release-template/verify-plugin-release.mjs", "repeatable owner proof");
requireText('verify-plugin-release.mjs --commit "${{ github.sha }}" --out dist-release --registry https://registry.npmjs.org/', "owner proof registry");
for (const value of ["spec_url:", "spec_sha256:", "${{ inputs.spec_url }}", "${{ inputs.spec_sha256 }}"]) requireText(value, "release-train input");
if (workflow.includes("repository: soksak-ai/soksak-spec")) throw new Error("release workflow must not checkout dependency source");
requireText("release-template/publish-canonical-release.mjs", "canonical immutable publisher");
requireText("GH_TOKEN: ${{ steps.release-token.outputs.token }}", "GitHub CLI release token");
requireText("node-version-file: soksak-plugins/soksak-plugin-terminal-vision/.node-version", "Node owner file");
requireText("package_json_file: soksak-plugins/soksak-plugin-terminal-vision/frontend/package.json", "pnpm owner file");
if (workflow.includes("pnpm --dir frontend") || workflow.includes("gh release create")) throw new Error("workflow bypasses the owner command or canonical publisher");
console.log("plugin release workflow contract: passed");
